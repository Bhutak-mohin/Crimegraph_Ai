  function executeAction(action) {
    if (!currentDossier) {
      showToast('Please analyze a case file first', 'error');
      return;
    }

    const d = currentDossier;

    // Build Case Object
    const caseObj = {
      id: d.id,
      title: d.title,
      status: 'Active',
      risk: d.risk,
      riskLevel: d.riskLevel,
      cluster: d.cluster,
      jurisdiction: d.jurisdiction,
      type: d.category,
      opened: d.date || 'Today',
      lastUpdate: 'Just now',
      desc: d.findings ? d.findings[0] : `Investigation registered under FIR ${d.id}`,
      suspects: d.entities.map(e => e.id),
      entities: d.entities.length,
      linkedCases: 2,
      icon: d.icon || '📁',
      timeline: d.timeline || [{ date: "Today", text: `FIR ${d.id} analyzed and registered.` }],
      findings: d.findings || [`Identified ${d.entities.length} related entities.`],
      recommendations: d.recommendations || ['Initiate surveillance on primary POI.']
    };

    // Build Forensic Report Object
    const mainPerson = d.entities.find(e => e.type === 'person') || d.entities[0];
    const reportObj = {
      id: `RPT-2024-${Math.floor(100 + Math.random() * 900)}`,
      name: `Forensic Dossier — ${d.title} (${d.id})`,
      case: d.id,
      date: 'Today',
      analyst: d.officer || 'Inspector Mehra',
      status: 'final',
      entityId: mainPerson ? mainPerson.id : null
    };

    // Ingest into shared data store and persist!
    CG.ingestCaseDossier({
      caseData: caseObj,
      entities: d.entities,
      links: d.links,
      predictions: d.predictions,
      report: reportObj
    });

    close();

    const mainTargetId = mainPerson ? mainPerson.id : d.entities[0].id;

    if (action === 'graph') {
      showToast(`Ingested ${d.id}: Opening Live Network Graph...`, 'ok');
      setTimeout(() => {
        location.href = `dashboard.html?case=${encodeURIComponent(d.id)}&entity=${encodeURIComponent(mainTargetId)}`;
      }, 350);
    } else if (action === 'case') {
      showToast(`Registered Case ${d.id}: Opening Case Management...`, 'ok');
      setTimeout(() => {
        location.href = `cases.html?open=${encodeURIComponent(d.id)}`;
      }, 350);
    } else if (action === 'disrupt') {
      showToast(`Targeting ${mainTargetId}: Launching Disruption Simulator...`, 'ok');
      setTimeout(() => {
        location.href = `dashboard.html?tab=predictive&entity=${encodeURIComponent(mainTargetId)}`;
      }, 350);
    } else if (action === 'predict') {
      showToast(`Opening GraphSAGE Predictive Intelligence...`, 'ok');
      setTimeout(() => {
        location.href = `dashboard.html?tab=predictive`;
      }, 350);
    } else if (action === 'report') {
      showToast(`Generating court evidence dossier for ${d.id}...`, 'ok');
      setTimeout(() => {
        location.href = `reports.html?case=${encodeURIComponent(d.id)}`;
      }, 350);
    } else if (action === 'json') {
      const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(d, null, 2));
      const downloadAnchor = document.createElement('a');
      downloadAnchor.setAttribute("href", dataStr);
      downloadAnchor.setAttribute("download", `CrimeGraph_Intelligence_${d.id}.json`);
      document.body.appendChild(downloadAnchor);
      downloadAnchor.click();
      downloadAnchor.remove();
      showToast(`Downloaded intelligence manifest for ${d.id}`, 'ok');
    }
  }


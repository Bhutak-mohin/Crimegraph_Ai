  function handleFile(file) {
    const reader = new FileReader();
    const isText = file.type.includes('text') || file.name.endsWith('.txt') || file.name.endsWith('.json') || file.name.endsWith('.csv') || file.name.endsWith('.md');
    
    showToast(`Reading digital case file: ${file.name}...`);
    
    if (isText) {
      reader.onload = e => {
        document.getElementById('uploader-text').value = e.target.result;
        updateCharCount();
        currentDossier = parseCustomDocument(e.target.result, file.name);
        document.querySelectorAll('.preset-card').forEach(c => c.classList.remove('active'));
        showToast(`Document parsed: ${file.name}. Click 'Analyse Case File' to proceed.`, 'ok');
      };
      reader.readAsText(file);
    } else {
      // PDF or binary scan simulation
      reader.onload = () => {
        const generated = parseCustomDocument(`STATE POLICE DIGITAL CASE ARCHIVE\nFile: ${file.name}\nSize: ${(file.size/1024).toFixed(1)} KB\nFIR: MH-2024-${Math.floor(1000+Math.random()*9000)}\nSections: BNS 111, 318, PMLA\nAccused: Tariq S. ('Falcon'), Devraj M., Nexus Frontline\nNarrative: Digital copy of police case file submitted via investigator terminal. Intercepted communications verify active financial and logistical operations between accused subjects across Maharashtra and Karnataka borders.`, file.name);
        document.getElementById('uploader-text').value = generated.rawText;
        updateCharCount();
        currentDossier = generated;
        document.querySelectorAll('.preset-card').forEach(c => c.classList.remove('active'));
        showToast(`Loaded ${file.name} (OCR pre-processed). Click 'Analyse Case File' to proceed.`, 'ok');
      };
      reader.readAsArrayBuffer(file);
    }
  }

